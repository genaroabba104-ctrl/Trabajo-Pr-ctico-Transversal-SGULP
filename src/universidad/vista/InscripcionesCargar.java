    private void btnInscribirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInscribirActionPerformed
        int idAlumno = Integer.parseInt(comboAlumno.getSelectedItem().toString().split(" - ")[0]);
        int idMateria = Integer.parseInt(comboMateria.getSelectedItem().toString().split(" - ")[0]);

        Inscripcion i = new Inscripcion();
        i.setAlumno(new AlumnoData().buscarAlumno(idAlumno));
        i.setMateria(new MateriaData().buscarMateria(idMateria));
        i.setCursa(anioSeleccion.getYear());
        i.setAsistencia(Integer.parseInt(textAsistencia.getText().trim()));
        i.setNota(0);

        new InscripcionData().guardarInscripcion(i);

        radioInscripto.setSelected(false);
        limpiarCampos();
        comboAlumno.setSelectedIndex(0);
    }//GEN-LAST:event_btnInscribirActionPerformed

