    private void anioSeleccionPropertyChange(java.beans.PropertyChangeEvent evt) {//GEN-FIRST:event_anioSeleccionPropertyChange
        if (!evt.getPropertyName().equals("year")) {
            return;
        }
        
        int anioActual = java.time.Year.now().getValue();
        int cursa = anioSeleccion.getYear();
        
        if (cursa < anioActual - 1 || cursa > anioActual + 1){
            JOptionPane.showMessageDialog(null,"El año debe estar entre " + (anioActual-1) + " y " + (anioActual+1));
            anioSeleccion.setYear(anioActual);
            return;
        }
        cargarComboMaterias();
    }//GEN-LAST:event_anioSeleccionPropertyChange

    private void btnDesinscribirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDesinscribirActionPerformed
        int idAlumno = Integer.parseInt(comboAlumno.getSelectedItem().toString().split(" - ")[0]);
        int idMateria = Integer.parseInt(comboMateria.getSelectedItem().toString().split(" - ")[0]);
        int cursa = anioSeleccion.getYear();
        
        int respuesta = JOptionPane.showConfirmDialog(this,
            "¿Seguro que desea dar de baja la inscripción?",
            "Confirmar", JOptionPane.YES_NO_OPTION);
        
        if(respuesta == JOptionPane.YES_OPTION){
            new InscripcionData().borrarInscripcion(idAlumno, idMateria, cursa);

            radioInscripto.setSelected(false);
            limpiarCampos();
            comboAlumno.setSelectedIndex(0);
        }
    }//GEN-LAST:event_btnDesinscribirActionPerformed

    private void cargarComboAlumno(){
        comboAlumno.removeAllItems();
        comboAlumno.addItem("Seleccione un alumno");
        AlumnoData aluData = new AlumnoData();
        List<Alumno> listaAlumnos = aluData.listarAlumnos();
        
        for(Alumno a: listaAlumnos){
            String cad = a.getIdAlumno() + " - " + a.getDni() + " - " + a.getApellido() + " " + a.getNombre();
            comboAlumno.addItem(cad);
        }
    }
    
    private void cargarComboMaterias(){
        comboMateria.removeAllItems();
        InscripcionData inscData = new InscripcionData();
        if(comboAlumno.getSelectedIndex() > 0){
            String cad = comboAlumno.getSelectedItem().toString();
            int cursa = anioSeleccion.getYear();
            comboMateria.setEnabled(true);
            anioSeleccion.setEnabled(true);
            
            // chequeo de radio
            if(radioInscripto.isSelected()){
                comboMateria.addItem("Materias inscriptas");
                int idAlumno = Integer.parseInt(cad.split(" - ")[0]);
                List<Materia> listaInscriptas = inscData.listarInscriptas(idAlumno, cursa);
                for(Materia m: listaInscriptas){
                    String combo = m.getIdMateria() + " - " + m.getNombre();
                    comboMateria.addItem(combo);
                }
            } else {
                comboMateria.addItem("Seleccione una materia");
                int idAlumno = Integer.parseInt(cad.split(" - ")[0]);
                List<Materia> listaNoInscriptas = inscData.listarNoInscriptas(idAlumno, cursa);
                for(Materia m: listaNoInscriptas){
                    String combo = m.getIdMateria() + " - " + m.getNombre();
                    comboMateria.addItem(combo);
                }
            }
        } else {
            comboMateria.addItem("Seleccione una materia");
            comboMateria.setEnabled(false);
            anioSeleccion.setEnabled(false);
        }
        actualizarEstado();
    }
    
    private void actualizarEstado(){
        boolean hayAlumno = comboAlumno.getSelectedIndex() > 0;
        boolean hayMateria = comboMateria.getSelectedIndex() > 0;
        boolean inscripto = radioInscripto.isSelected();
        
        textAsistencia.setEnabled(hayAlumno && hayMateria && !inscripto);
        btnInscribir.setEnabled(hayAlumno && hayMateria && !inscripto && asistenciaValida());
        btnDesinscribir.setEnabled(hayAlumno && hayMateria && inscripto);
    }
    
    private boolean asistenciaValida(){
        try {
            int a = Integer.parseInt(textAsistencia.getText().trim());
            return a >= 0 && a <= 100;
        } catch (NumberFormatException e){
            return false;
        }
    }
    
    private void deshabilitar(){
        comboMateria.setEnabled(false);
        anioSeleccion.setEnabled(false);
        textAsistencia.setEnabled(false);
        btnInscribir.setEnabled(false);
    }
    
    private void limpiarCampos(){
        textAsistencia.setText("");
        anioSeleccion.setYear(java.time.Year.now().getValue());
    }
