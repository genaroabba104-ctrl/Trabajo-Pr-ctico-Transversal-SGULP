    private void cargarCabecera(){
        modelo.addColumn("ID Inscripción");
        modelo.addColumn("Materia");
        modelo.addColumn("Nota");
        modelo.addColumn("Año");
        modelo.addColumn("Asistencia");
        
        tableInscripciones.setModel(modelo);
    }
    
    private void cargarComboAlumno(){
        comboAlumno.removeAllItems();
        comboAlumno.addItem("Seleccione un alumno");
        AlumnoData aluData = new AlumnoData();
        List<Alumno> listaAlumnos = aluData.listarAlumnos();
            
        for(Alumno a: listaAlumnos){
            String cadena = a.getIdAlumno() + " - " + a.getApellido() + " " + a.getNombre();
            comboAlumno.addItem(cadena);
        }
    }
    
    private void cargarTabla(){
        modelo.setNumRows(0);
        if(comboAlumno.getSelectedIndex() > 0){
            InscripcionData inscData = new InscripcionData();
            AlumnoData aluData = new AlumnoData();
            String a = comboAlumno.getSelectedItem().toString();
            int idAlumno = Integer.parseInt(a.split(" - ")[0]);
            int anioCursa = anioSeleccion.getYear();
            Alumno alumno = aluData.buscarAlumno(idAlumno);
            List<Inscripcion> listaInscripciones = inscData.listarInscripciones(alumno, anioCursa);
            
            if(listaInscripciones.size() > 0){
                for(Inscripcion i: listaInscripciones){
                    if (i.getNota() > 0){
                        modelo.addRow(new Object[]{
                            i.getIdInscripcion(),
                            i.getMateria().getNombre(),
                            i.getNota(),
                            i.getCursa(),
                            i.getAsistencia() + "%"
                        }); 
                    } else {
                        modelo.addRow(new Object[]{
                            i.getIdInscripcion(),
                            i.getMateria().getNombre(),
                            "No hay nota cargada",
                            i.getCursa(),
                            i.getAsistencia() + "%"
                        });
                    }
                    
                }
            } else {
                JOptionPane.showMessageDialog(null, "No hay materias inscriptas");
            }
        }
    }
    
