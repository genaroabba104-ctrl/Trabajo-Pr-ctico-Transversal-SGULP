    private void btnCargarNotaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarNotaActionPerformed
        int fila = tableInscripciones.getSelectedRow();
        if(fila < 0){
            JOptionPane.showMessageDialog(null, "Debe seleccionar una fila");
            return;
        }
        
        double nota;
        try{
            nota = Double.parseDouble(textNota.getText().trim().replace(",", "."));
            
        } catch (NumberFormatException e){
            JOptionPane.showMessageDialog(this, "La nota debe ser un número (ej: 8.5).");
            return;
        }
        
        if(nota < 0 || nota > 10){
            JOptionPane.showMessageDialog(this, "La nota debe estar entre 0 y 10.");
            return;
        }
        
        int idInscripcion = (int) modelo.getValueAt(fila, 0);
        new InscripcionData().actualizarNota(idInscripcion, nota);
        
        cargarTabla();
        textNota.setText("");
        textNota.setEnabled(false);
        btnCargarNota.setEnabled(false);
    }//GEN-LAST:event_btnCargarNotaActionPerformed

